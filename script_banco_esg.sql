-- ==============================================================================
-- MODELAGEM DE DADOS: EFICIENCIA ENERGETICA E SUSTENTABILIDADE (ESG)
-- ==============================================================================

-- 1. Tabela de Localidades
CREATE TABLE LOCALIDADE (
    ID_LOCALIDADE NUMBER PRIMARY KEY,
    NOME_SETOR VARCHAR2(100) NOT NULL,
    TIPO_AMBIENTE VARCHAR2(50)
);

-- 2. Tabela de Equipamentos
CREATE TABLE EQUIPAMENTO (
    ID_EQUIPAMENTO NUMBER PRIMARY KEY,
    ID_LOCALIDADE NUMBER,
    NOME_EQUIP VARCHAR2(100) NOT NULL,
    STATUS_ATUAL VARCHAR2(20) DEFAULT 'INATIVO', 
    TOTAL_KWH_ACUMULADO NUMBER(10, 2) DEFAULT 0,
    CONSTRAINT FK_EQUIP_LOCAL FOREIGN KEY (ID_LOCALIDADE) REFERENCES LOCALIDADE(ID_LOCALIDADE)
);

-- 3. Tabela de Sensores IoT
CREATE TABLE SENSOR_IOT (
    ID_SENSOR NUMBER PRIMARY KEY,
    ID_EQUIPAMENTO NUMBER,
    LIMITE_ALERTA_KWH NUMBER(8, 2) NOT NULL,
    CONSTRAINT FK_SENSOR_EQUIP FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES EQUIPAMENTO(ID_EQUIPAMENTO)
);

-- 4. Tabela de Leituras (Eventos enviados pelos sensores)
CREATE TABLE LEITURA_ENERGIA (
    ID_LEITURA NUMBER PRIMARY KEY,
    ID_SENSOR NUMBER,
    DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    VALOR_KWH NUMBER(8, 2) NOT NULL,
    CONSTRAINT FK_LEITURA_SENSOR FOREIGN KEY (ID_SENSOR) REFERENCES SENSOR_IOT(ID_SENSOR)
);

-- 5. Tabela de Alertas de Consumo Excessivo
CREATE TABLE ALERTA_CONSUMO (
    ID_ALERTA NUMBER PRIMARY KEY,
    ID_SENSOR NUMBER,
    DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DESCRICAO VARCHAR2(255),
    STATUS_ALERTA VARCHAR2(20) DEFAULT 'ATIVO',
    CONSTRAINT FK_ALERTA_SENSOR FOREIGN KEY (ID_SENSOR) REFERENCES SENSOR_IOT(ID_SENSOR)
);

-- Sequence para o Alerta
CREATE SEQUENCE SEQ_ALERTA START WITH 1 INCREMENT BY 1;


-- ==============================================================================
-- AUTOMACOES COM TRIGGERS (PL/SQL)
-- ==============================================================================

-- Automação 1: Geração de Alerta se o limite estourar
CREATE OR REPLACE TRIGGER TRG_GERAR_ALERTA_ESG
AFTER INSERT ON LEITURA_ENERGIA
FOR EACH ROW
DECLARE
    V_LIMITE NUMBER;
BEGIN
    SELECT LIMITE_ALERTA_KWH INTO V_LIMITE 
      FROM SENSOR_IOT 
     WHERE ID_SENSOR = :NEW.ID_SENSOR;
    
    IF :NEW.VALOR_KWH > V_LIMITE THEN
        INSERT INTO ALERTA_CONSUMO (ID_ALERTA, ID_SENSOR, DATA_HORA, DESCRICAO, STATUS_ALERTA)
        VALUES (
            SEQ_ALERTA.NEXTVAL, 
            :NEW.ID_SENSOR, 
            :NEW.DATA_HORA, 
            'Desperdício Ambiental: Consumo (' || :NEW.VALOR_KWH || ' kWh) acima da meta de ' || V_LIMITE, 
            'ATIVO'
        );
    END IF;
END;
/

-- Automação 2: Atualizar Status Operacional (Ativo/Inativo)
CREATE OR REPLACE TRIGGER TRG_ATUALIZA_STATUS_EQUIP
AFTER INSERT ON LEITURA_ENERGIA
FOR EACH ROW
DECLARE
    V_ID_EQUIPAMENTO NUMBER;
BEGIN
    SELECT ID_EQUIPAMENTO INTO V_ID_EQUIPAMENTO 
      FROM SENSOR_IOT 
     WHERE ID_SENSOR = :NEW.ID_SENSOR;

    IF :NEW.VALOR_KWH > 0 THEN
        UPDATE EQUIPAMENTO SET STATUS_ATUAL = 'ATIVO' 
         WHERE ID_EQUIPAMENTO = V_ID_EQUIPAMENTO;
    ELSE
        UPDATE EQUIPAMENTO SET STATUS_ATUAL = 'INATIVO' 
         WHERE ID_EQUIPAMENTO = V_ID_EQUIPAMENTO;
    END IF;
END;
/

-- Automação 3: Baixar/Resolver alertas antigos se a energia normalizou
CREATE OR REPLACE TRIGGER TRG_RESOLVER_ALERTA_ANTIGO
AFTER INSERT ON LEITURA_ENERGIA
FOR EACH ROW
DECLARE
    V_LIMITE NUMBER;
BEGIN
    SELECT LIMITE_ALERTA_KWH INTO V_LIMITE 
      FROM SENSOR_IOT 
     WHERE ID_SENSOR = :NEW.ID_SENSOR;
     
    IF :NEW.VALOR_KWH <= V_LIMITE THEN
        UPDATE ALERTA_CONSUMO
           SET STATUS_ALERTA = 'RESOLVIDO',
               DESCRICAO = DESCRICAO || ' (Normalizado)'
         WHERE ID_SENSOR = :NEW.ID_SENSOR 
           AND STATUS_ALERTA = 'ATIVO';
    END IF;
END;
/

-- Automação 4: Acumular/Totalizar consumo no perfil do Equipamento
CREATE OR REPLACE TRIGGER TRG_ACUMULAR_CONSUMO_ESG
AFTER INSERT ON LEITURA_ENERGIA
FOR EACH ROW
DECLARE
    V_ID_EQUIPAMENTO NUMBER;
BEGIN
    SELECT ID_EQUIPAMENTO INTO V_ID_EQUIPAMENTO 
      FROM SENSOR_IOT 
     WHERE ID_SENSOR = :NEW.ID_SENSOR;

    UPDATE EQUIPAMENTO
       SET TOTAL_KWH_ACUMULADO = TOTAL_KWH_ACUMULADO + :NEW.VALOR_KWH
     WHERE ID_EQUIPAMENTO = V_ID_EQUIPAMENTO;
END;
/
